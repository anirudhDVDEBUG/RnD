#!/usr/bin/env python3
"""
Mythos Skill Forge — scaffold production-ready Claude Code skills.

Generates a complete skill directory with SKILL.md, CLAUDE.md, hooks,
and templates following Anthropic's skill conventions.
"""

import argparse
import os
import re
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path


@dataclass
class SkillSpec:
    """Specification for a Claude Code skill."""
    name: str
    title: str
    description: str
    triggers: list[str]
    steps: list[str]
    category: str = "general"
    hooks: bool = False
    templates: bool = False

    def validate(self) -> list[str]:
        """Validate the skill spec against Anthropic conventions."""
        errors = []
        if not re.match(r"^[a-z][a-z0-9_]{0,58}$", self.name):
            errors.append(f"Name '{self.name}' must be snake_case, start with a letter, max 60 chars")
        if len(self.triggers) < 3:
            errors.append(f"Need at least 3 trigger phrases, got {len(self.triggers)}")
        if len(self.triggers) > 5:
            errors.append(f"Recommend at most 5 trigger phrases, got {len(self.triggers)}")
        if len(self.steps) < 2:
            errors.append(f"Need at least 2 workflow steps, got {len(self.steps)}")
        if not self.description.strip():
            errors.append("Description cannot be empty")
        if len(self.description) > 500:
            errors.append(f"Description too long ({len(self.description)} chars), max 500")
        return errors


def generate_skill_md(spec: SkillSpec) -> str:
    """Generate the SKILL.md content."""
    trigger_list = ", ".join(f'"{t}"' for t in spec.triggers)
    when_to_use = "\n".join(f'- "{t}"' for t in spec.triggers)
    steps_md = "\n".join(f"### Step {i+1}: {s}" for i, s in enumerate(spec.steps))

    return textwrap.dedent(f"""\
    ---
    name: {spec.name}
    description: |
      {spec.description}
      Triggers: {trigger_list}
    ---

    # {spec.title}

    {spec.description}

    ## When to use

    {when_to_use}

    ## How to use

    {steps_md}

    ## References

    - Generated by Mythos Skill Forge
    - Anthropic skill conventions: https://github.com/anthropics/skills
    """)


def generate_claude_md(spec: SkillSpec) -> str:
    """Generate a CLAUDE.md for the skill directory."""
    return textwrap.dedent(f"""\
    # {spec.title} — Agent Instructions

    This skill was generated by Mythos Skill Forge.

    ## Context

    - **Category**: {spec.category}
    - **Triggers**: {', '.join(spec.triggers)}

    ## Behavior

    When triggered, follow the steps in SKILL.md exactly.
    Do not skip validation or output steps.

    ## Constraints

    - Stay within the skill's scope — do not perform unrelated actions.
    - If a step fails, report the failure clearly before continuing.
    - Prefer generating files over printing to stdout for large outputs.
    """)


def generate_hook(hook_type: str, spec: SkillSpec) -> str:
    """Generate a pre or post hook script."""
    if hook_type == "pre":
        return textwrap.dedent(f"""\
        #!/bin/sh
        # Pre-execution hook for {spec.name}
        # Runs before the skill executes.
        echo "[{spec.name}] Pre-hook: validating environment..."
        # Add pre-checks here (e.g., required tools, files, permissions)
        exit 0
        """)
    else:
        return textwrap.dedent(f"""\
        #!/bin/sh
        # Post-execution hook for {spec.name}
        # Runs after the skill completes.
        echo "[{spec.name}] Post-hook: cleaning up..."
        # Add post-processing here (e.g., formatting, notifications)
        exit 0
        """)


def generate_template(spec: SkillSpec) -> str:
    """Generate a default output template."""
    return textwrap.dedent(f"""\
    # {{{{ title }}}}

    > Generated by **{spec.title}**

    ## Summary

    {{{{ summary }}}}

    ## Details

    {{{{ details }}}}

    ---
    _Produced by {spec.name} skill_
    """)


def forge_skill(spec: SkillSpec, output_dir: Path, dry_run: bool = False) -> dict:
    """
    Forge a complete skill directory structure.

    Returns a dict of {relative_path: content} for all generated files.
    """
    errors = spec.validate()
    if errors:
        return {"_errors": errors}

    skill_dir = output_dir / spec.name
    files = {}

    # Core files
    files[f"{spec.name}/SKILL.md"] = generate_skill_md(spec)
    files[f"{spec.name}/CLAUDE.md"] = generate_claude_md(spec)

    # Optional hooks
    if spec.hooks:
        files[f"{spec.name}/hooks/pre_run.sh"] = generate_hook("pre", spec)
        files[f"{spec.name}/hooks/post_run.sh"] = generate_hook("post", spec)

    # Optional templates
    if spec.templates:
        files[f"{spec.name}/templates/default.md"] = generate_template(spec)

    if dry_run:
        return files

    # Write files to disk
    for rel_path, content in files.items():
        full_path = output_dir / rel_path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(content)
        if rel_path.endswith(".sh"):
            full_path.chmod(0o755)

    return files


def audit_skill(skill_dir: Path) -> dict:
    """
    Audit an existing skill directory for convention compliance.

    Returns a report dict with score and issues.
    """
    report = {"path": str(skill_dir), "score": 0, "max_score": 5, "issues": [], "passes": []}

    skill_md = skill_dir / "SKILL.md"
    if not skill_md.exists():
        report["issues"].append("Missing SKILL.md")
        return report

    content = skill_md.read_text()

    # Check 1: YAML frontmatter with name and description
    if content.startswith("---"):
        fm_end = content.find("---", 3)
        if fm_end > 0:
            frontmatter = content[3:fm_end]
            if "name:" in frontmatter and "description:" in frontmatter:
                report["passes"].append("YAML frontmatter has name and description")
                report["score"] += 1
            else:
                report["issues"].append("Frontmatter missing 'name' or 'description'")
            if "Triggers:" in frontmatter or "triggers:" in frontmatter.lower():
                report["passes"].append("Triggers defined in frontmatter")
                report["score"] += 1
            else:
                report["issues"].append("No trigger phrases in frontmatter description")
        else:
            report["issues"].append("Malformed YAML frontmatter (no closing ---)")
    else:
        report["issues"].append("Missing YAML frontmatter")

    # Check 2: When to use section
    if "## When to use" in content:
        when_section = content.split("## When to use")[1].split("##")[0]
        bullet_count = when_section.count("\n-")
        if bullet_count >= 3:
            report["passes"].append(f"'When to use' has {bullet_count} trigger phrases")
            report["score"] += 1
        else:
            report["issues"].append(f"'When to use' has only {bullet_count} triggers (need 3+)")
    else:
        report["issues"].append("Missing '## When to use' section")

    # Check 3: How to use section
    if "## How to use" in content:
        report["passes"].append("'How to use' section present")
        report["score"] += 1
    else:
        report["issues"].append("Missing '## How to use' section")

    # Check 4: No placeholder text
    placeholders = ["TODO", "FIXME", "placeholder", "<your", "lorem ipsum"]
    found = [p for p in placeholders if p.lower() in content.lower()]
    if not found:
        report["passes"].append("No placeholder text detected")
        report["score"] += 1
    else:
        report["issues"].append(f"Placeholder text found: {', '.join(found)}")

    return report


def print_report(report: dict):
    """Pretty-print an audit report."""
    print(f"\n{'='*60}")
    print(f"  Skill Audit: {report['path']}")
    print(f"  Score: {report['score']}/{report['max_score']}")
    print(f"{'='*60}")
    if report["passes"]:
        print("\n  PASS:")
        for p in report["passes"]:
            print(f"    [+] {p}")
    if report["issues"]:
        print("\n  ISSUES:")
        for i in report["issues"]:
            print(f"    [-] {i}")
    print()


def print_tree(files: dict, base: str = ""):
    """Print a directory tree of generated files."""
    print(f"\n  Generated skill structure:")
    print(f"  {'='*40}")
    for path in sorted(files.keys()):
        if path.startswith("_"):
            continue
        depth = path.count("/")
        indent = "  " * depth
        name = path.split("/")[-1]
        print(f"    {indent}{name}")
    print()


