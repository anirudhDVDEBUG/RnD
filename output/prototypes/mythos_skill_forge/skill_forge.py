def main():
    parser = argparse.ArgumentParser(
        description="Mythos Skill Forge — scaffold Claude Code skills",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
        Examples:
          %(prog)s forge --name my_skill --desc "Does X" --triggers "do X,run X,X please"
          %(prog)s forge --preset code_review
          %(prog)s audit ./skills/my_skill
          %(prog)s list-presets
        """),
    )
    sub = parser.add_subparsers(dest="command", help="Command to run")

    # forge
    forge_p = sub.add_parser("forge", help="Scaffold a new skill")
    forge_p.add_argument("--name", help="Skill name (snake_case)")
    forge_p.add_argument("--title", help="Human-readable title")
    forge_p.add_argument("--desc", help="Skill description")
    forge_p.add_argument("--triggers", help="Comma-separated trigger phrases")
    forge_p.add_argument("--steps", help="Comma-separated workflow steps")
    forge_p.add_argument("--preset", choices=PRESETS.keys(), help="Use a preset skill template")
    forge_p.add_argument("--hooks", action="store_true", help="Generate hook scripts")
    forge_p.add_argument("--templates", action="store_true", help="Generate output templates")
    forge_p.add_argument("--output", default="./skills", help="Output directory (default: ./skills)")
    forge_p.add_argument("--dry-run", action="store_true", help="Preview without writing files")

    # audit
    audit_p = sub.add_parser("audit", help="Audit an existing skill directory")
    audit_p.add_argument("path", help="Path to skill directory")

    # list-presets
    sub.add_parser("list-presets", help="Show available preset templates")

    # demo
    sub.add_parser("demo", help="Run a full demo: forge presets + audit them")

    args = parser.parse_args()

    if args.command == "forge":
        if args.preset:
            spec = PRESETS[args.preset]
        elif args.name and args.desc and args.triggers:
            spec = SkillSpec(
                name=args.name,
                title=args.title or args.name.replace("_", " ").title(),
                description=args.desc,
                triggers=[t.strip() for t in args.triggers.split(",")],
                steps=[s.strip() for s in (args.steps or "Execute the skill workflow,Report results").split(",")],
                hooks=args.hooks,
                templates=args.templates,
            )
        else:
            forge_p.error("Provide --preset OR (--name, --desc, --triggers)")
            return

        output_dir = Path(args.output)
        print(f"\n  Forging skill: {spec.name}")
        print(f"  Output: {output_dir / spec.name}")

        files = forge_skill(spec, output_dir, dry_run=args.dry_run)

        if "_errors" in files:
            print("\n  Validation errors:")
            for e in files["_errors"]:
                print(f"    [-] {e}")
            sys.exit(1)

        print_tree(files)

        if args.dry_run:
            print("  (dry-run mode — no files written)\n")
            for path, content in sorted(files.items()):
                print(f"  --- {path} ---")
                for line in content.split("\n")[:10]:
                    print(f"  | {line}")
                print(f"  | ... ({len(content.split(chr(10)))} lines total)\n")
        else:
            print(f"  Wrote {len(files)} files.\n")

            # Auto-audit
            skill_path = output_dir / spec.name
            report = audit_skill(skill_path)
            print_report(report)

    elif args.command == "audit":
        path = Path(args.path)
        if not path.is_dir():
            print(f"Error: {path} is not a directory")
            sys.exit(1)
        report = audit_skill(path)
        print_report(report)

    elif args.command == "list-presets":
        print("\n  Available presets:")
        print(f"  {'='*50}")
        for key, spec in PRESETS.items():
            print(f"    {key:20s} — {spec.description[:60]}")
        print()

    elif args.command == "demo":
        print("\n" + "="*60)
        print("  MYTHOS SKILL FORGE — FULL DEMO")
        print("="*60)

        output_dir = Path("./demo_output/skills")
        print(f"\n  Output directory: {output_dir}\n")

        # Forge all presets
        for key, spec in PRESETS.items():
            print(f"  >> Forging preset: {key}")
            files = forge_skill(spec, output_dir)
            print_tree(files)

        # Forge a custom skill
        custom = SkillSpec(
            name="ticket_triage",
            title="Ticket Triage Agent",
            description="Automatically categorizes and prioritizes support tickets using context analysis.",
            triggers=[
                "triage this ticket",
                "categorize incoming tickets",
                "prioritize support queue",
            ],
            steps=[
                "Parse the ticket content and metadata",
                "Classify by category (bug, feature, question, billing)",
                "Assign priority (P0-P3) based on impact and urgency",
                "Route to the appropriate team or escalation path",
                "Generate triage summary with reasoning",
            ],
            category="support",
            hooks=True,
            templates=True,
        )
        print(f"  >> Forging custom skill: {custom.name}")
        files = forge_skill(custom, output_dir)
        print_tree(files)

        # Audit all generated skills
        print("\n" + "="*60)
        print("  AUDIT RESULTS")
        print("="*60)

        total_score = 0
        total_max = 0
        for skill_dir in sorted(output_dir.iterdir()):
            if skill_dir.is_dir():
                report = audit_skill(skill_dir)
                print_report(report)
                total_score += report["score"]
                total_max += report["max_score"]

        print(f"\n  Overall: {total_score}/{total_max} across {total_max // 5} skills")
        pct = (total_score / total_max * 100) if total_max else 0
        grade = "A" if pct >= 90 else "B" if pct >= 80 else "C" if pct >= 70 else "F"
        print(f"  Grade: {grade} ({pct:.0f}%)\n")

    else:
        parser.print_help()


if __name__ == "__main__":
    main()
