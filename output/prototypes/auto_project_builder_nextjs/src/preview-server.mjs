#!/usr/bin/env node
/**
 * Lightweight preview server — serves the generated project's
 * page.tsx as a static HTML preview (no Next.js runtime needed).
 * Used by run.sh to show something visual without npm install.
 */

import fs from "fs";
import path from "path";
import http from "http";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = path.resolve(__dirname, "..", "generated_project");

function extractPageContent() {
  const pagePath = path.join(OUTPUT_DIR, "src/app/page.tsx");
  const layoutPath = path.join(OUTPUT_DIR, "src/app/layout.tsx");

  if (!fs.existsSync(pagePath)) {
    return "<h1>No generated project found. Run the builder first.</h1>";
  }

  const pkg = JSON.parse(
    fs.readFileSync(path.join(OUTPUT_DIR, "package.json"), "utf-8")
  );

  // Read page to extract items
  const pageContent = fs.readFileSync(pagePath, "utf-8");
  const titleMatch = pageContent.match(/title: "([^"]+)"/g) || [];
  const entityMatch = pageContent.match(/Your (\w+)s/) || ["", "Item"];
  const entity = entityMatch[1];

  const items = [];
  const itemRegex = /title: "([^"]+)", description: "([^"]+)"/g;
  let m;
  while ((m = itemRegex.exec(pageContent)) !== null) {
    items.push({ title: m[1], desc: m[2] });
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${pkg.name} — Preview</title>
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    body { font-family: system-ui, -apple-system, sans-serif; background: #fafafa; color: #111; }
    header { border-bottom: 1px solid #e5e7eb; padding: 1rem 1.5rem; }
    header h1 { font-size: 1.25rem; }
    header p { font-size: 0.875rem; color: #6b7280; }
    main { max-width: 56rem; margin: 0 auto; padding: 1.5rem; }
    .top { display: flex; justify-content: space-between; align-items: center; margin-bottom: 1.5rem; }
    .top h2 { font-size: 1.5rem; font-weight: 700; }
    .btn { display: inline-flex; align-items: center; padding: 0.5rem 1rem; font-size: 0.875rem; font-weight: 500; background: #111827; color: white; border: none; border-radius: 0.375rem; cursor: pointer; }
    .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(240px, 1fr)); gap: 1rem; }
    .card { background: white; border: 1px solid #e5e7eb; border-radius: 0.5rem; padding: 1.25rem; box-shadow: 0 1px 2px rgba(0,0,0,0.05); }
    .card h3 { font-size: 1rem; font-weight: 600; margin-bottom: 0.5rem; }
    .card p { font-size: 0.875rem; color: #6b7280; }
    .badge { display: inline-block; font-size: 0.7rem; background: #dbeafe; color: #1e40af; padding: 0.15rem 0.5rem; border-radius: 9999px; margin-top: 0.5rem; }
    footer { text-align: center; padding: 2rem; font-size: 0.75rem; color: #9ca3af; }
  </style>
</head>
<body>
  <header>
    <h1>${pkg.name.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase())}</h1>
    <p>Auto-generated Next.js + shadcn/ui + SQLite project</p>
  </header>
  <main>
    <div class="top">
      <h2>Your ${entity}s</h2>
      <button class="btn">Add ${entity}</button>
    </div>
    <div class="grid">
      ${items
        .map(
          (it) => `
      <div class="card">
        <h3>${it.title}</h3>
        <p>${it.desc}</p>
        <span class="badge">SQLite</span>
      </div>`
        )
        .join("\n")}
    </div>
  </main>
  <footer>
    Generated by auto-project-builder | Next.js + shadcn/ui + SQLite
  </footer>
</body>
</html>`;
}

const PORT = parseInt(process.env.PORT || "3456", 10);
const server = http.createServer((req, res) => {
  res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
  res.end(extractPageContent());
});

server.listen(PORT, () => {
  console.log(`Preview server running at http://localhost:${PORT}`);
  console.log("Press Ctrl+C to stop.");
});
